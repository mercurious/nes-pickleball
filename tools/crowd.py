#!/usr/bin/env python3
"""Writes audio/crowd.pently: applause as Pently noise effects. A crowd of clappers, each clapping 3-4 times a
second with its own jitter; every clap is a burst of bright noise that dies in a frame or two. The frames' summed
intensity becomes the noise volume under an envelope (a quick swell, a hold, a long fade), and the noise pitch
wanders over the bright end, so it crackles instead of hissing. Deterministic (a fixed seed).
Usage: crowd.py > audio/crowd.pently"""
import random

def applause(name, frames, clappers, peak, seed):
    rnd = random.Random(seed)
    inten = [0.0] * frames
    for _ in range(clappers):
        t = rnd.uniform(0, 8)
        rate = rnd.uniform(3.0, 4.2)
        loud = rnd.uniform(0.5, 1.0)
        while t < frames:
            i = int(t)
            inten[i] += loud
            if i + 1 < frames: inten[i + 1] += loud * 0.35
            t += 60 / rate * rnd.uniform(0.85, 1.15)
    rise, fall = 10, frames * 2 // 3
    vols, pitches = [], []
    for i, v in enumerate(inten):
        env = min(1.0, i / rise) * (1.0 if i < frames - fall else (frames - i) / fall)
        vols.append(max(0, min(15, round(peak * env * min(1.0, v / 2.2)))))
        pitches.append(rnd.choice((10, 11, 11, 12, 12, 13)))
    while vols and vols[-1] == 0: vols.pop()
    return "sfx %s on noise\n  volume %s\n  pitch %s\n" % (name, " ".join(map(str, vols)), " ".join(map(str, pitches[:len(vols)])))

print("# Generated by tools/crowd.py: applause as noise effects. Do not edit by hand.\n")
print(applause("applause", 150, 14, 9, 20261011))
print(applause("applause_big", 220, 22, 11, 20261012))
