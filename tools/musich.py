#!/usr/bin/env python3
"""Writes the numbers of the score's songs (PS_) and sound effects (PE_) from Pently's output (build/music.s) as a
C header, so src/sound.c can name them. Usage: musich.py build/music.s > build/music.h"""
import sys, re
songs, sfx = [], []
for line in open(sys.argv[1]):
    m = re.match(r"\s*sfxdef\s+(PE_\w+)", line)
    if m: sfx.append(m.group(1))
    m = re.match(r"\s*songdef\s+(PS_\w+)", line)
    if m: songs.append(m.group(1))
print("/* generated by tools/musich.py from build/music.s */")
for i, n in enumerate(sfx): print("#define %s %d" % (n, i))
for i, n in enumerate(songs): print("#define %s %d" % (n, i))
