def tiles():
    """the font as a list of 8x8 tiles (rows of ints), index = position in ORDER"""
    out = []
    for ch in ORDER:
        t = [[1] * 8 for _ in range(8)]
        if ch != ' ':
            for r, row in enumerate(G[ch]):
                for c, px in enumerate(row):
                    if px == '#':
                        t[r][c + 1] = 2
        out.append(t)
    return out

def tile_of(ch):
    return ORDER.index(ch)

