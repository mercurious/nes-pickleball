#!/usr/bin/env python3
"""Sprites from text to CHR (8x16 pairs in pattern table 1) plus sprdefs.h and a preview PNG.
Usage: chr.py art/sprites.txt build
Format: '@NAME W H' then H rows of W chars, '.'=transparent, '1','2','3' = palette colours.
A 16-wide frame is laid out as 4 pairs: col0 top, col0 bottom, col1 top, col1 bottom (H padded to 32 at the top);
an 8-wide one as one pair (H padded to 16). SPR_NAME is the odd tile index of its first pair."""
import sys, os
src, out = sys.argv[1], sys.argv[2]
frames = []
with open(src) as f:
    lines = [l.rstrip("\n") for l in f]
i = 0
while i < len(lines):
    l = lines[i].strip()
    if l.startswith("@"):
        name, w, h = l[1:].split()
        w, h = int(w), int(h)
        rows = [lines[i + 1 + k].ljust(w, ".")[:w] for k in range(h)]
        frames.append((name, w, h, rows))
        i += 1 + h
    else:
        i += 1

def px(ch):
    return 0 if ch == "." else int(ch)

tiles = []            # 8x8 tiles in order: pair k = tiles 2k (top) and 2k+1 (bottom)
defs = []
for name, w, h, rows in frames:
    H = 32 if w > 8 else 16
    pad = H - h
    canvas = [["."] * w for _ in range(pad)] + [list(r) for r in rows]
    base_pair = len(tiles) // 2
    for col in range(0, w, 8):
        for top in range(0, H, 16):
            for sub in (0, 8):
                tile = [[px(canvas[top + sub + r][col + c]) for c in range(8)] for r in range(8)]
                tiles.append(tile)
    defs.append((name, base_pair * 2 + 1, w, h))
assert len(tiles) <= 256, "too many sprite tiles: %d" % len(tiles)

def encode(t):
    lo = bytes(sum(((t[r][c] & 1) << (7 - c)) for c in range(8)) for r in range(8))
    hi = bytes(sum(((t[r][c] >> 1) << (7 - c)) for c in range(8)) for r in range(8))
    return lo + hi

chr_data = b"".join(encode(t) for t in tiles) + b"\0" * (16 * (256 - len(tiles)))
os.makedirs(out, exist_ok=True)
open(os.path.join(out, "spr.chr"), "wb").write(chr_data)
with open(os.path.join(out, "sprdefs.h"), "w") as f:
    f.write("/* generated by tools/chr.py: tile index (odd: pattern table 1, 8x16) of each frame's first pair */\n")
    for name, t, w, h in defs:
        f.write("#define SPR_%s 0x%02X\n" % (name, t))
    f.write("#define SPR_TILE_COUNT %d\n" % len(tiles))

try:
    from PIL import Image
    cols = [(0, 0, 0, 0), (255, 200, 160, 255), (255, 255, 255, 255), (20, 20, 20, 255)]
    n = len(tiles) // 2
    img = Image.new("RGBA", (n * 8, 16), (90, 90, 120, 255))
    for k in range(n):
        for sub in (0, 1):
            t = tiles[2 * k + sub]
            for r in range(8):
                for c in range(8):
                    if t[r][c]:
                        img.putpixel((k * 8 + c, sub * 8 + r), cols[t[r][c]])
    img = img.resize((img.width * 4, img.height * 4), Image.NEAREST)
    img.save(os.path.join(out, "sprites.png"))
except ImportError:
    pass
print("sprites: %d frames, %d tiles of 256" % (len(frames), len(tiles)))
