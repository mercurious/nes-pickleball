#!/usr/bin/env python3
"""RAM symbols from the ld65 debug file: build/ramsyms.json {name: address} for the tests and the sidecar,
and docs/RAM_MAP.md. Usage: ramsyms.py build/pickleball.dbg build/ramsyms.json [docs/RAM_MAP.md]"""
import re, sys, json
dbg, out = sys.argv[1], sys.argv[2]
syms = {}
for line in open(dbg):
    if not line.startswith("sym"):
        continue
    f = dict(kv.split("=", 1) for kv in line[4:].strip().split(","))
    name = f.get("name", "").strip('"')
    if not name.startswith("_") or "val" not in f or f.get("type") != "lab":
        continue
    val = int(f["val"], 16)
    size = int(f.get("size", "1"))
    if val < 0x800:
        syms[name[1:]] = {"addr": val, "size": size}
json.dump(syms, open(out, "w"), indent=0, sort_keys=True)
if len(sys.argv) > 3:
    with open(sys.argv[3], "w") as f:
        f.write("# RAM map (generated by tools/ramsyms.py from the build)\n\nAddresses are NES CPU addresses; ints are 16-bit little-endian 8.8 fixed point (256 = 1 px).\n\n| address | size | name |\n|---|---|---|\n")
        for n, v in sorted(syms.items(), key=lambda kv: kv[1]["addr"]):
            f.write("| $%04X | %d | %s |\n" % (v["addr"], v["size"], n))
print("ramsyms: %d symbols" % len(syms))
