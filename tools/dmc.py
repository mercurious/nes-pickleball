#!/usr/bin/env python3
"""WAV words to NES DPCM: 1-bit delta modulation at one of the APU's 16 rates, the way the DMC decodes it
(a 7-bit level that steps +2 or -2 per bit, LSB first). Usage: dmc.py RATE_INDEX OUT.bin OUT.h name=file.wav ...
Each sample is 64-byte aligned, 16n+1 bytes long, at most 4081 bytes; OUT.h has the address and length registers."""
import sys, wave, struct, os
RATES = [4182, 4710, 5264, 5593, 6258, 7046, 8363, 9420, 11186, 12604, 13983, 16885, 18634, 22372, 26584, 33144]
idx = int(sys.argv[1]); out_bin, out_h = sys.argv[2], sys.argv[3]
rate = RATES[idx]

def read_wav(path):
    w = wave.open(path, "rb")
    n, ch, sw, sr = w.getnframes(), w.getnchannels(), w.getsampwidth(), w.getframerate()
    raw = w.readframes(n); w.close()
    fmt = {1: "b", 2: "h", 4: "i"}[sw]
    data = struct.unpack("<%d%s" % (n * ch, fmt), raw)
    if sw == 1: data = [(x - 128) for x in data]
    mono = [sum(data[i * ch:(i + 1) * ch]) / ch for i in range(n)]
    peak = max(1.0, max(abs(x) for x in mono))
    return [x / peak for x in mono], sr

def resample(x, sr, target):
    out, n = [], int(len(x) * target / sr)
    for i in range(n):
        p = i * sr / target; j = int(p); f = p - j
        a = x[j] if j < len(x) else 0.0; b = x[j + 1] if j + 1 < len(x) else a
        out.append(a + (b - a) * f)
    return out

def trim(x, thr=0.02):
    i, j = 0, len(x)
    while i < j and abs(x[i]) < thr: i += 1
    while j > i and abs(x[j - 1]) < thr: j -= 1
    return x[max(0, i - 40): j + 40]

def encode(x):
    """samples in -1..1 -> DPCM bytes; the decoder's level starts at 64 and steps by 2"""
    level, bits = 64, []
    for v in x:
        target = 64 + int(v * 56)
        if target > level: bit = 1; level = min(126, level + 2)
        else: bit = 0; level = max(0, level - 2)
        bits.append(bit)
    while len(bits) % 8: bits.append(len(bits) & 1)
    data = bytearray()
    for i in range(0, len(bits), 8):
        data.append(sum(bits[i + k] << k for k in range(8)))
    while (len(data) - 1) % 16: data.append(0x55)           # 16n + 1 bytes; 0x55 holds the level steady
    return bytes(data[:4081])

blob = bytearray(); table = []
for arg in sys.argv[4:]:
    name, path = arg.split("=", 1)
    x, sr = read_wav(path)
    y = trim(resample(x, sr, rate))
    # a touch of pre-emphasis helps consonants survive the 1-bit coding
    y = [y[i] - 0.3 * (y[i - 1] if i else 0.0) for i in range(len(y))]
    d = encode(y)
    while len(blob) % 64: blob.append(0x55)
    table.append((name, len(blob), len(d)))
    blob += d
    print("%-10s %5d bytes %.2f s" % (name, len(d), len(d) * 8 / rate))
open(out_bin, "wb").write(bytes(blob))
with open(out_h, "w") as f:
    f.write("/* generated by tools/dmc.py: DPCM words at %d Hz (rate index %d); offsets within the DMC segment */\n" % (rate, idx))
    f.write("#define SPEECH_RATE %d\n#define SPEECH_WORDS %d\n#define SPEECH_BYTES %d\n" % (idx, len(table), len(blob)))
    f.write("#ifdef SPEECH_TABLES\n")
    f.write("static const unsigned char SPEECH_OFF[%d] = {%s};\n" % (len(table), ",".join(str(o // 64) for _, o, _ in table)))
    f.write("static const unsigned char SPEECH_LEN[%d] = {%s};\n" % (len(table), ",".join(str((l - 1) // 16) for _, _, l in table)))
    f.write("#endif\n")
    for i, (name, _, _) in enumerate(table): f.write("#define W_%s %d\n" % (name.upper(), i))
print("speech: %d words, %d bytes" % (len(table), len(blob)))
